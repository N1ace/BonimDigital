  function convert(value,lang,map=HE,rev=reverse){
    if(!value) return value;
    const source=rev.get(value)||value;
    return lang==='he'?(map[source]||source):source;
  }
  function replacePreservingSpace(value,lang){
    const clean=value.trim();
    if(!clean) return value;
    const next=convert(clean,lang);
    return next===clean?value:value.replace(clean,next);
  }
  function translateNode(node,lang){
    if(node.parentElement&&node.parentElement.closest('script,style,.logo-word,[data-i18n-skip]')) return;
    const next=replacePreservingSpace(node.nodeValue,lang);
    if(next!==node.nodeValue) node.nodeValue=next;
  }
  function translateElement(el,lang){
    if(el.nodeType!==1||el.matches('[data-language-switch],.logo-word,[data-i18n-skip]')) return;
    if(el.hasAttribute('data-i18n')){
      const key=el.getAttribute('data-i18n');
      const next=convert(key,lang);
      if(el.childElementCount===0&&el.textContent.trim()!==next) el.textContent=next;
    }
    attrs.forEach(attr=>{
      if(!el.hasAttribute(attr)) return;
      const value=el.getAttribute(attr);
      const next=convert(value,lang);
      if(next!==value) el.setAttribute(attr,next);
    });
  }
  function walk(root,lang){
    if(root.nodeType===3){translateNode(root,lang);return;}
    if(root.nodeType!==1&&root.nodeType!==9&&root.nodeType!==11) return;
    if(root.nodeType===1) translateElement(root,lang);
    const walker=document.createTreeWalker(root,NodeFilter.SHOW_ELEMENT|NodeFilter.SHOW_TEXT);
    let node;
    while((node=walker.nextNode())){
      if(node.nodeType===3) translateNode(node,lang);
      else translateElement(node,lang);
    }
  }
